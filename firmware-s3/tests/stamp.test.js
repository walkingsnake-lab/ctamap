'use strict';
// scripts/stamp-firmware-version.js: the commit fits the server's health
// field rule (letters, digits, `_`, `:`; contract: /board/version).

const test = require('node:test');
const assert = require('node:assert/strict');
const { version, header } = require('../../scripts/stamp-firmware-version');

test('firmware version stamp passes the health field rule', () => {
  const v = version();
  assert.match(v, /^([0-9a-f]{7}(_dirty)?|dev)$/);
  assert.equal(header('a1b2c3d'), '// Generated by scripts/stamp-firmware-version.js. Do not edit or commit.\n#define FIRMWARE_VERSION "a1b2c3d"\n');
});
