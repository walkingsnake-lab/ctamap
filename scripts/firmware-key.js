#!/usr/bin/env node
'use strict';
// Makes the key OTA builds are signed with, and sets up CI to use it
// (firmware-s3/README.md, "Signed builds"). Run once, on your own computer:
//
//   node scripts/firmware-key.js --github
//
// 1. The private key: ~/.ctaboard/firmware-signing-key.pem (ECDSA P-256),
//    made once and reused after. Back it up (a password manager): without
//    it, new builds can only reach boards over USB.
// 2. The public key, into the repo: firmware-s3/firmware-signing.pub.pem
//    (the server checks uploads with it) and
//    firmware-s3/ctaboard/src/signing_key.h (boards check builds with it).
//    Commit both.
// 3. --github: a GitHub environment, firmware-release, that only main can
//    use, holding FIRMWARE_SIGNING_KEY and a new FIRMWARE_DEPLOY_TOKEN (the
//    token CI publishes beta builds with). Prints the `fly secrets set`
//    command that gives the server the same deploy token.

const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const REPO = 'walkingsnake-lab/ctamap';
const ENV = 'firmware-release';
const KEY_FILE = path.join(os.homedir(), '.ctaboard', 'firmware-signing-key.pem');
const PUB_FILE = path.join(ROOT, 'firmware-s3', 'firmware-signing.pub.pem');
const HEADER_FILE = path.join(ROOT, 'firmware-s3', 'ctaboard', 'src', 'signing_key.h');

// src/signing_key.h for a public key PEM ("" when there's none yet).
function headerFor(pem) {
  const body = pem ? pem.trim().split('\n').map((l) => `    "${l}\\n"`).join('\n') : '    ""';
  return '// Generated by scripts/firmware-key.js from firmware-s3/firmware-signing.pub.pem. Do not edit.\n'
    + '// The public key OTA builds are signed with. Empty: no key made yet, and the\n'
    + '// board installs no OTA build (it can still be flashed over USB).\n'
    + '#pragma once\n'
    + `static const char FIRMWARE_SIGNING_KEY[] =\n${body};\n`;
}

// The public key in the repo, or null.
function repoPublicKey() {
  try { return fs.readFileSync(PUB_FILE, 'utf8'); } catch (e) { return null; }
}

function gh(args, input) {
  const r = spawnSync('gh', args, { encoding: 'utf8', input });
  return { ok: r.status === 0, out: (r.stdout || '') + (r.stderr || '') };
}

function setUpGithub(privatePem) {
  if (!gh(['--version']).ok) throw new Error('the GitHub CLI (gh) is needed for --github');
  // An environment only main can deploy from: a workflow edited on another
  // branch can't read its secrets.
  let r = gh(['api', '-X', 'PUT', `repos/${REPO}/environments/${ENV}`, '-F', 'deployment_branch_policy[protected_branches]=false', '-F', 'deployment_branch_policy[custom_branch_policies]=true']);
  if (!r.ok) throw new Error(`creating the ${ENV} environment failed: ${r.out.trim()}`);
  r = gh(['api', '-X', 'POST', `repos/${REPO}/environments/${ENV}/deployment-branch-policies`, '-f', 'name=main', '-f', 'type=branch']);
  if (!r.ok && !/already exists/i.test(r.out)) throw new Error(`limiting ${ENV} to main failed: ${r.out.trim()}`);
  r = gh(['secret', 'set', 'FIRMWARE_SIGNING_KEY', '--env', ENV, '-R', REPO], privatePem);
  if (!r.ok) throw new Error(`setting FIRMWARE_SIGNING_KEY failed: ${r.out.trim()}`);
  const deploy = crypto.randomBytes(24).toString('base64url');
  r = gh(['secret', 'set', 'FIRMWARE_DEPLOY_TOKEN', '--env', ENV, '-R', REPO], deploy);
  if (!r.ok) throw new Error(`setting FIRMWARE_DEPLOY_TOKEN failed: ${r.out.trim()}`);
  return deploy;
}

function main(argv) {
  const github = argv.includes('--github');
  if (argv.includes('-h') || argv.includes('--help')) {
    console.log('node scripts/firmware-key.js [--github]   (see the comment at the top)');
    return 0;
  }
  let privatePem;
  if (fs.existsSync(KEY_FILE)) {
    privatePem = fs.readFileSync(KEY_FILE, 'utf8');
    console.log(`Using the existing key: ${KEY_FILE}`);
  } else {
    const { privateKey } = crypto.generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
    privatePem = privateKey.export({ type: 'pkcs8', format: 'pem' });
    fs.mkdirSync(path.dirname(KEY_FILE), { recursive: true, mode: 0o700 });
    fs.writeFileSync(KEY_FILE, privatePem, { mode: 0o600 });
    console.log(`New signing key: ${KEY_FILE}\n  Back it up now (a password manager). Without it, new builds reach boards only over USB.`);
  }
  const publicPem = crypto.createPublicKey(privatePem).export({ type: 'spki', format: 'pem' });
  const before = repoPublicKey();
  if (before && before.trim() !== publicPem.trim()) {
    console.warn('! The repo had a different public key. Boards running builds with the old key reject builds signed with this one until they get a build with it over USB.');
  }
  fs.writeFileSync(PUB_FILE, publicPem);
  fs.writeFileSync(HEADER_FILE, headerFor(publicPem));
  console.log(`Public key written: ${path.relative(ROOT, PUB_FILE)}, ${path.relative(ROOT, HEADER_FILE)} (commit both)`);
  if (github) {
    const deploy = setUpGithub(privatePem);
    console.log(`GitHub: environment ${ENV} (main only) has FIRMWARE_SIGNING_KEY and FIRMWARE_DEPLOY_TOKEN.`);
    console.log(`Give the server the same deploy token:\n  fly secrets set FIRMWARE_DEPLOY_TOKEN=${deploy}`);
  } else {
    console.log('Next: run again with --github to set up CI (needs gh).');
  }
  return 0;
}

module.exports = { headerFor, PUB_FILE, HEADER_FILE, KEY_FILE };

if (require.main === module) {
  try { process.exitCode = main(process.argv.slice(2)); } catch (e) { console.error(`firmware-key: ${e.message}`); process.exitCode = 1; }
}
