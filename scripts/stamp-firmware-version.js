'use strict';
// Writes firmware-s3/ctaboard/version.h with the commit the S3 firmware is
// built from, so the board reports it in health (`hv`, contract:
// /board/version) and the control page's Health tab shows it. Run before each
// Arduino build: node scripts/stamp-firmware-version.js
//
// The short commit, plus `_dirty` when the working tree has uncommitted
// changes; `dev` outside a git checkout. version.h is gitignored.

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'firmware-s3', 'ctaboard', 'version.h');

function git(args) {
  const r = spawnSync('git', args, { cwd: ROOT, encoding: 'utf8' });
  return r.status === 0 ? r.stdout.trim() : null;
}

function version() {
  const commit = git(['rev-parse', '--short=7', 'HEAD']);
  if (!commit) return 'dev';
  const dirty = git(['status', '--porcelain', '--untracked-files=no']);
  return commit + (dirty ? '_dirty' : '');
}

function header(v) {
  return '// Generated by scripts/stamp-firmware-version.js. Do not edit or commit.\n' +
    `#define FIRMWARE_VERSION "${v}"\n`;
}

module.exports = { version, header };

if (require.main === module) {
  const v = version();
  fs.writeFileSync(OUT, header(v));
  console.log(`${path.relative(ROOT, OUT)}: ${v}`);
}
