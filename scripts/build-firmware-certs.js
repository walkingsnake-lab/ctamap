#!/usr/bin/env node
'use strict';
// Generates firmware-s3/ctaboard/src/certs.h: the root certificates the S3
// board trusts for HTTPS (one PEM bundle; mbedTLS reads every certificate in
// it). A handful of the big public roots, so the board keeps verifying the
// server if its certificate moves to another of these CAs:
//   node scripts/build-firmware-certs.js [/etc/ssl/certs]
// Reads the PEMs from the system store (Debian/Ubuntu layout).

const fs = require('fs');
const path = require('path');

const ROOTS = [
  'ISRG_Root_X1', 'ISRG_Root_X2',                 // Let's Encrypt
  'GTS_Root_R1', 'GTS_Root_R4',                   // Google Trust Services
  'DigiCert_Global_Root_G2',                      // DigiCert
  'USERTrust_RSA_Certification_Authority', 'USERTrust_ECC_Certification_Authority',  // Sectigo
  'Amazon_Root_CA_1',                             // Amazon
];
const OUT = path.join(__dirname, '..', 'firmware-s3', 'ctaboard', 'src', 'certs.h');

function build(dir) {
  const lines = [
    '// Generated by scripts/build-firmware-certs.js. Do not edit by hand.',
    '// Root certificates the board trusts for HTTPS, as one PEM bundle:',
    `//   ${ROOTS.join(', ')}`,
    '#pragma once',
    '',
    'static const char ROOT_CAS[] =',
  ];
  for (const name of ROOTS) {
    const pem = fs.readFileSync(path.join(dir, name + '.pem'), 'utf8').trim();
    if (!/^-----BEGIN CERTIFICATE-----[\s\S]+-----END CERTIFICATE-----$/.test(pem)) throw new Error(`${name}: not a single PEM certificate`);
    lines.push(`    // ${name}`);
    for (const l of pem.split('\n')) lines.push(`    "${l}\\n"`);
  }
  lines.push('    ;', '');
  return lines.join('\n');
}

if (require.main === module) {
  fs.writeFileSync(OUT, build(process.argv[2] || '/etc/ssl/certs'));
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}
module.exports = { build, OUT, ROOTS };
