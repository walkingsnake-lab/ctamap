#!/usr/bin/env node
'use strict';
// Generates firmware/boardlib/assets.py from the server's board fonts, icons,
// and glyph codepoints, so the board draws with exactly the same data as
// server/board/draw.js. Run after any font, icon, or glyph change:
//   node scripts/build-firmware-assets.js
// (A test fails if the committed file is stale.)

const fs = require('fs');
const path = require('path');
const { packFonts } = require('../server/board/fonts');
const icons = require('../server/board/icons');
const glyphs = require('../server/board/glyphs');

const OUT = path.join(__dirname, '..', 'firmware', 'boardlib', 'assets.py');
const rgb = (hex) => `(${parseInt(hex.slice(1, 3), 16)}, ${parseInt(hex.slice(3, 5), 16)}, ${parseInt(hex.slice(5, 7), 16)})`;

function build() {
  const fonts = packFonts();
  const lines = [
    '# Generated by scripts/build-firmware-assets.js from server/board/fonts,',
    '# icons.js and glyphs.js. Do not edit by hand.',
    '#',
    '# FONTS[name][codepoint] = (dwidth, w, h, xoff, yoff, row0bits, row1bits, ...)',
    '# Row bits are MSB-left within the glyph width.',
    '',
    'FONTS = {',
  ];
  for (const name of Object.keys(fonts).sort()) {
    lines.push(`    '${name}': {`);
    for (const cp of Object.keys(fonts[name]).map(Number).sort((a, b) => a - b)) {
      lines.push(`        ${cp}: (${fonts[name][cp].join(', ')}),`);
    }
    lines.push('    },');
  }
  lines.push('}', '');
  lines.push('ICON_PALETTE = {');
  for (const [k, v] of Object.entries(icons.PALETTE)) lines.push(`    '${k}': ${rgb(v)},`);
  lines.push('}', '');
  lines.push('ICONS = {');
  for (const [k, rows] of Object.entries(icons.ICONS)) lines.push(`    '${k}': (${rows.map((r) => `'${r}'`).join(', ')}),`);
  lines.push('}', '');
  lines.push(`ALERT_BANG = (${icons.ALERT_BANG.map((r) => `'${r}'`).join(', ')})`, '');
  for (const [k, v] of Object.entries(glyphs)) if (typeof v === 'number') lines.push(`${k} = ${v}`);
  return lines.join('\n') + '\n';
}

if (require.main === module) {
  fs.writeFileSync(OUT, build());
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}
module.exports = { build, OUT };
