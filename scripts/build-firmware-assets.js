#!/usr/bin/env node
'use strict';
// Generates firmware/boardlib/assets.py from the server's board fonts, icons,
// and glyph codepoints, so the board draws with exactly the same data as
// server/board/draw.js. Run after any font, icon, or glyph change:
//   node scripts/build-firmware-assets.js
// (A test fails if the committed file is stale.)

const fs = require('fs');
const path = require('path');
const { packFonts } = require('../server/board/fonts');
const icons = require('../server/board/icons');
const glyphs = require('../server/board/glyphs');

const OUT = path.join(__dirname, '..', 'firmware', 'boardlib', 'assets.py');
const rgb = (hex) => `(${parseInt(hex.slice(1, 3), 16)}, ${parseInt(hex.slice(3, 5), 16)}, ${parseInt(hex.slice(5, 7), 16)})`;

// Fonts are packed into one bytes object each, because in CircuitPython
// every tuple costs a heap object: ~210 glyph tuples in dicts took ~15 KB of
// the board's ~150 KB heap; packed they take ~4 KB. Per glyph record:
//   dwidth, w, h, xoff + 128, yoff + 128, then h rows of ceil(w / 8) bytes
//   (big-endian, MSB-left within the glyph width; at least 1 byte per row).
// FONT_LOW / FONT_PUA map codepoints 32-255 and PUA..PUA+15 to 2-byte
// big-endian record offsets (0xFFFF: no glyph).
const LOW0 = 32, LOW_N = 224, PUA_N = 16, NONE = 0xffff;

function packFont(font, pua) {
  const data = [];
  const low = new Array(LOW_N).fill(NONE), hi = new Array(PUA_N).fill(NONE);
  for (const cp of Object.keys(font).map(Number).sort((a, b) => a - b)) {
    const [dw, w, h, xo, yo, ...rows] = font[cp];
    if (w > 16) throw new Error(`glyph ${cp} is ${w} px wide; rows hold at most 16`);
    if (xo < -128 || xo > 127 || yo < -128 || yo > 127 || dw > 255 || h > 255) throw new Error(`glyph ${cp} out of range`);
    const at = data.length;
    if (at >= NONE) throw new Error('font data over 64 KB');
    if (cp >= LOW0 && cp < LOW0 + LOW_N) low[cp - LOW0] = at;
    else if (cp >= pua && cp < pua + PUA_N) hi[cp - pua] = at;
    else throw new Error(`codepoint ${cp} outside the packed ranges`);
    const rb = Math.max(1, Math.ceil(w / 8));
    data.push(dw, w, h, xo + 128, yo + 128);
    for (const bits of rows) for (let k = rb - 1; k >= 0; k--) data.push((bits >> (8 * k)) & 255);
  }
  const be16 = (arr) => arr.flatMap((v) => [v >> 8, v & 255]);
  return { data, low: be16(low), hi: be16(hi) };
}

const pyBytes = (arr) => "b'" + arr.map((v) => '\\x' + v.toString(16).padStart(2, '0')).join('') + "'";

function build() {
  const fonts = packFonts();
  const pua = glyphs.TT;
  const lines = [
    '# Generated by scripts/build-firmware-assets.js from server/board/fonts,',
    '# icons.js and glyphs.js. Do not edit by hand.',
    '#',
    '# Packed to save heap (a tuple per glyph cost ~15 KB). FONT_DATA[name]',
    '# holds glyph records: dwidth, w, h, xoff + 128, yoff + 128, then h rows',
    '# of max(1, ceil(w / 8)) bytes (big-endian, MSB-left within the width).',
    `# FONT_LOW[name] / FONT_PUA[name]: 2-byte big-endian record offsets for`,
    `# codepoints ${LOW0}-${LOW0 + LOW_N - 1} and PUA..PUA+${PUA_N - 1}; 0xFFFF = no glyph.`,
    '# Read them with draw.glyph() / draw.glyph_row().',
    '',
    `PUA = ${pua}`,
    `LOW0 = ${LOW0}`,
    '',
  ];
  const packed = {};
  for (const name of Object.keys(fonts).sort()) packed[name] = packFont(fonts[name], pua);
  for (const [key, field] of [['FONT_DATA', 'data'], ['FONT_LOW', 'low'], ['FONT_PUA', 'hi']]) {
    lines.push(`${key} = {`);
    for (const name of Object.keys(packed)) lines.push(`    '${name}': ${pyBytes(packed[name][field])},`);
    lines.push('}', '');
  }
  // Icons: 8 x 8, one byte per pixel (the palette letter's code, '.' = 46
  // for none), row by row; the palette is keyed by that code.
  lines.push('ICON_PALETTE = {');
  for (const [k, v] of Object.entries(icons.PALETTE)) lines.push(`    ${k.charCodeAt(0)}: ${rgb(v)},  # ${k}`);
  lines.push('}', '');
  lines.push('ICONS = {');
  for (const [k, rows] of Object.entries(icons.ICONS)) {
    if (rows.length !== 8 || rows.some((r) => r.length !== 8)) throw new Error(`icon ${k} is not 8 x 8`);
    lines.push(`    '${k}': b'${rows.join('')}',`);
  }
  lines.push('}', '');
  lines.push(`ALERT_BANG = (${icons.ALERT_BANG.map((r) => `'${r}'`).join(', ')})`, '');
  for (const [k, v] of Object.entries(glyphs)) if (typeof v === 'number') lines.push(`${k} = ${v}`);
  return lines.join('\n') + '\n';
}

if (require.main === module) {
  fs.writeFileSync(OUT, build());
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}
module.exports = { build, OUT };
